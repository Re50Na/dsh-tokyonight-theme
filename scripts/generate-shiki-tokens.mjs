import { readFileSync, writeFileSync } from 'node:fs'
const palettes = JSON.parse(readFileSync(new URL('../data/tokyonight-palette.json', import.meta.url), 'utf8'))
const tokens = {}
for (const [id, palette] of Object.entries(palettes)) {
  const p = Object.fromEntries(Object.entries(palette.colors).map(([name, value]) => [name, value.hex]))
  const base = {
    '--shiki-foreground': 'var(--dsw-alias-label-primary)',
    '--shiki-background': 'var(--dsw-alias-markdown-code-block)',
    '--shiki-token-constant': p.peach,
    '--shiki-token-string': p.green,
    '--shiki-token-comment': p.comment,
    '--shiki-token-keyword': p.mauve,
    '--shiki-token-parameter': p.parameter,
    '--shiki-token-function': p.blue,
    '--shiki-token-string-expression': p.green,
    '--shiki-token-punctuation': p.syntaxText,
    '--shiki-token-link': p.teal,
  }
  tokens[id] = { default: base }
}
writeFileSync(new URL('../src/client/shiki-tokens.ts', import.meta.url), `/** AUTO-GENERATED by scripts/generate-shiki-tokens.mjs. Source: TokyoNightPalette.md. */
import type { TokyoNightFlavorId } from './palettes.ts'
export type ShikiTokenName = ${Object.keys(tokens.light.default).map(k => JSON.stringify(k)).join(' | ')}
export type ShikiTokens = Record<ShikiTokenName, string>
export const SHIKI_TOKENS: Record<TokyoNightFlavorId, Record<'default', ShikiTokens>> = ${JSON.stringify(tokens,null,2)}
`)
